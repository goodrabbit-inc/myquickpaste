def apply_patch(data: dict, p: dict) -> None:
    pain = data.setdefault("pain", {})
    pain["titleLine1"] = p["pain_title_line1"]
    pain["titleLine2"] = p["pain_title_line2"]
    pain["lead"] = p["pain_lead"]
    pain["p1Title"] = p["pain_p1_title"]
    pain["p1Text"] = p["pain_p1_text"]
    pain["p2Title"] = p["pain_p2_title"]
    pain["p2Text"] = p["pain_p2_text"]
    pain["p3Title"] = p["pain_p3_title"]
    pain["p3Text"] = p["pain_p3_text"]

    hero = data.setdefault("hero", {})
    hero["lead"] = p["hero_lead"]
    hero["sub"] = p["hero_sub"]

    privacy = data.setdefault("privacySection", {})
    privacy["titleLine1"] = p["privacy_title_line1"]
    privacy["titleLine2"] = p["privacy_title_line2"]
    privacy["text"] = p["privacy_text"]

    cta = data.setdefault("cta", {})
    cta["titleLine1"] = p["cta_title_line1"]
    cta["titleLine2"] = p["cta_title_line2"]
    cta["lead"] = p["cta_lead"]
    # cta.sub: left unchanged (trial message; see patch_license_i18n.py)

    data["sceneMore"] = {
        "titleLine1": p["scene_more_title_line1"],
        "titleLine2": p["scene_more_title_line2"],
        "lead": p["scene_more_lead"],
        "cap3": p["scene_more_cap3"],
        "cap4": p["scene_more_cap4"],
        "cap6": p["scene_more_cap6"],
    }

    trust = data.setdefault("trust", {})
    trust["t3Text"] = p["trust_t3_text"]


def main() -> None:
    if len(ALL) != 21:
        print(f"ERROR: expected 21 languages, got {len(ALL)}", file=sys.stderr)
        sys.exit(1)
    for lang in LANGS:
        if lang not in ALL:
            print(f"ERROR: missing translations for {lang}", file=sys.stderr)
            sys.exit(1)
        path = I18N_DIR / f"{lang}.json"
        data = json.loads(path.read_text(encoding="utf-8"))
        apply_patch(data, ALL[lang])
        path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        print(f"Patched {path.name} ({len(PATCHED_KEYS)} keys + sceneMore object)")


if __name__ == "__main__":
    main()
